import proedis from 'eslint-config-proedis';


/* --------
 * @proedis/ui
 * -------- */

const UI = 'packages/ui/src';

const UI_DOCS = 'apps/platform/src';

/** The sections of @proedis/ui, in the order they may depend on each other: each imports only from earlier ones */
const UI_SECTIONS = [ 'core', 'layout', 'primitives', 'internal', 'actions', 'display', 'feedback', 'forms', 'overlays', 'data' ];

/**
 * Where layout comes from the layout primitives only: every section but `layout`, which is where those
 * classes are written, once. The sections joined one by one while their containers moved onto Stack,
 * Cluster and Grid; now all of them are in.
 */
const UI_LAYOUT_LOCKED = UI_SECTIONS.filter((section) => section !== 'layout').concat('hooks');

/** A display class (`flex`, `inline-flex`, `grid`, `inline-grid`), with or without variants */
const DISPLAY = String.raw`(?:^|\s)(?:[^\s:]+:)*(?:inline-)?(?:flex|grid)(?:\s|$)`;
const DISPLAY_ALONE = String.raw`^(?:[^\s:]+:)*(?:inline-)?(?:flex|grid)$`;
const GAP = String.raw`(?:^|\s)(?:[^\s:]+:)*gap-(?:[xy]-)?\S`;

const LAYOUT_MESSAGE = 'Layout written by hand. Use Stack, Cluster or Grid from layout, with their props (direction, '
  + 'gap, align, justify, wrap, inline, columns). An exception needs an eslint-disable comment saying why the primitives '
  + 'cannot express it.';

/** The selectors of the layout rule, shared by the block that locks the sections and by its exemption below */
const LAYOUT_SELECTORS = [
  { message: LAYOUT_MESSAGE, selector: `Literal[value=/${DISPLAY}/][value=/\\s/]` },
  { message: LAYOUT_MESSAGE, selector: `JSXAttribute[name.name='className'] Literal[value=/${DISPLAY_ALONE}/]` },
  { message: LAYOUT_MESSAGE, selector: `CallExpression[callee.name='cn'] > Literal[value=/${DISPLAY_ALONE}/]` },
  { message: LAYOUT_MESSAGE, selector: `TemplateElement[value.raw=/${DISPLAY}/]` },
  { message: LAYOUT_MESSAGE, selector: `Literal[value=/${GAP}/]` },
  { message: LAYOUT_MESSAGE, selector: `TemplateElement[value.raw=/${GAP}/]` }
];

/**
 * The height of a control, `h-control-sm|md|lg`, with or without variants. `min-h-control-*` is not it:
 * a label lined up with a field reads the height without being a control.
 */
const CONTROL_HEIGHT_CLASS = String.raw`(?:^|\s)(?:[^\s:]+:)*h-control-`;

const CONTROL_HEIGHT_MESSAGE = 'A control height written by hand. Compose it from CONTROL_HEIGHT in internal/control: two '
  + 'controls of the same size must have the same height, and that map is the one place it is written.';

const CONTROL_HEIGHT_SELECTORS = [
  { message: CONTROL_HEIGHT_MESSAGE, selector: `Literal[value=/${CONTROL_HEIGHT_CLASS}/]` },
  { message: CONTROL_HEIGHT_MESSAGE, selector: `TemplateElement[value.raw=/${CONTROL_HEIGHT_CLASS}/]` }
];


/**
 * An outline width with a variant (`focus-visible:outline-2`) and no style on the same variant. In
 * Tailwind 4 the width writes `outline-style: var(--tw-outline-style)`, and `outline-none` sets that
 * variable to `none`, so next to it the width draws nothing. The whole package shipped that way until
 * it was measured. Pairing them in one string is the house rule, so a component that splits its
 * classes across constants still carries the style where the width is. The style may come before or
 * after; `outline-none` on the same variant counts, being a decision about the style too.
 */
const OUTLINE_STYLE = String.raw`outline-(?:solid|dashed|dotted|double|none|hidden)(?=\s|$)`;
const OUTLINE_WIDTH_ALONE = String.raw`(?:^|\s)(\S+:)outline(?:-\d+)?(?=\s|$)`
  + String.raw`(?![\s\S]*(?:^|\s)\1${OUTLINE_STYLE})(?<!(?:^|\s)\1${OUTLINE_STYLE}[\s\S]*)`;

const OUTLINE_MESSAGE = 'An outline width with no style on the same variant: next to outline-none it draws nothing. '
  + 'Add the style beside it, e.g. focus-visible:outline-2 focus-visible:outline-solid.';

const OUTLINE_SELECTORS = [
  { message: OUTLINE_MESSAGE, selector: `Literal[value=/${OUTLINE_WIDTH_ALONE}/]` },
  { message: OUTLINE_MESSAGE, selector: `TemplateElement[value.raw=/${OUTLINE_WIDTH_ALONE}/]` }
];


/**
 * The suite lints itself with the config it publishes.
 *
 * The React preset is used for every package, not only the React ones: its extra rules only ever
 * fire on JSX, and running a single configuration over the whole repository is worth more than the
 * handful of rules it adds where there is no JSX to check.
 */
export default proedis.defineConfig(
  proedis.react({
    /** Library code has to be safe in both environments, so both sets of globals are declared */
    globals: [ 'browser', 'node' ],

    /** Pinned rather than detected: the root pin is what every package is built against */
    reactVersion: '19',

    ignores: [
      /** Generated from eslint-config-airbnb-base, rebuilt with 'yarn rules:sync' */
      '**/lib/airbnb/**',

      /** Generated by the TanStack Router plugin on every run of the documentation site */
      'apps/platform/src/routeTree.gen.ts'
    ]
  }),

  /** The build tooling is CommonJS, and the repository root has no 'type' field to say so */
  proedis.configs.commonjs([ 'scripts/**/*.js' ]),

  {
    /**
     * The generator resolves an Airbnb rule file per iteration, which is a dynamic require by
     * definition — there is no static specifier that could enumerate eight files.
     */
    name : 'suite/rules-generator',
    files: [ 'scripts/sync-airbnb-rules.mjs' ],
    rules: {
      'import/no-dynamic-require': [ 'off' ]
    }
  },

  {
    /**
     * The sections of @proedis/ui depend one way: a section imports from the ones before it and never
     * from the ones after. The resolver is told about TypeScript, or the rule resolves nothing and
     * passes in silence.
     */
    name    : 'suite/ui-sections',
    files   : [ `${UI}/**/*.{ts,tsx}` ],
    settings: {
      'import/resolver': { node: { extensions: [ '.ts', '.tsx', '.js', '.mjs' ] } }
    },
    rules: {
      /*
       * One order for every import block of the package, so a reader sees the dependencies of a file in
       * the order of the sections: React, the packages, @proedis, then each section from core to data,
       * the modules of the same section, the files of the same module, and the types last in the same
       * order. A group per section keeps a cross-section dependency visible at a glance.
       */
      'import/order': [ 'error', {
        groups    : [ 'builtin', 'external', 'internal', 'parent', 'sibling', 'index', 'type' ],
        pathGroups: [
          { pattern: 'react', group: 'external', position: 'before' },
          { pattern: '@proedis/**', group: 'external', position: 'after' },
          ...[ ...UI_SECTIONS, 'hooks' ].map((section) => ({
            pattern : `{../,../../,../../../}${section}/**`,
            group   : 'parent',
            position: 'before'
          }))
        ],
        pathGroupsExcludedImportTypes: [ 'builtin' ],
        distinctGroup                : true,
        'newlines-between'           : 'always',
        sortTypesGroup               : true,
        'newlines-between-types'     : 'always',
        alphabetize                  : { order: 'asc', caseInsensitive: true }
      } ],
      'import/no-restricted-paths': [ 'error', {
        zones: [
          ...UI_SECTIONS.slice(0, -1).map((section, index) => ({
            target : `./${UI}/${section}`,
            from   : UI_SECTIONS.slice(index + 1).map((later) => `./${UI}/${later}`),
            message: `'${section}' may import only from the sections before it: ${UI_SECTIONS.slice(0, index).join(', ') || 'none'}.`
          })),
          {
            target : `./${UI}/hooks`,
            from   : UI_SECTIONS.slice(1).map((section) => `./${UI}/${section}`),
            message: 'The hooks of @proedis/ui may import only from core.'
          }
        ]
      } ]
    }
  },

  ...(UI_LAYOUT_LOCKED.length ? [ {
    /**
     * In a locked section a container is a layout primitive, never a class string that rebuilds one.
     * The selectors of the shared Tailwind block come first because this rule replaces it for these
     * files rather than adding to it.
     */
    name : 'suite/ui-layout',
    files: UI_LAYOUT_LOCKED.map((section) => `${UI}/${section}/**/*.{ts,tsx}`),
    rules: {
      'no-restricted-syntax': [
        ...proedis.configs.tailwind.rules['no-restricted-syntax'],
        ...LAYOUT_SELECTORS,
        ...CONTROL_HEIGHT_SELECTORS,
        ...OUTLINE_SELECTORS
      ]
    }
  }, {
    /** The one module allowed to write a control height: the map every control reads it from */
    name : 'suite/ui-control-height',
    files: [ `${UI}/internal/control.ts` ],
    rules: {
      'no-restricted-syntax': [
        ...proedis.configs.tailwind.rules['no-restricted-syntax'],
        ...LAYOUT_SELECTORS,
        ...OUTLINE_SELECTORS
      ]
    }
  } ] : []),

  {
    /**
     * One frame for every bordered control: the classes of the frame, its sizes, its gap and its states
     * are read by `FieldShell` alone, and Textarea, the one control that is its own frame, reads the
     * states. A control that wrote them itself would be a second frame, a step off the others.
     */
    name   : 'suite/ui-field-shell',
    files  : [ `${UI}/**/*.{ts,tsx}` ],
    ignores: [ `${UI}/forms/field-shell/**`, `${UI}/forms/textarea/**`, `${UI}/forms/text-control/**` ],
    rules  : {
      'no-restricted-imports': [ 'error', {
        patterns: [ {
          group      : [ '**/text-control/textControl' ],
          importNames: [ 'TEXT_CONTROL_FRAME', 'TEXT_CONTROL_SELF', 'TEXT_CONTROL_SIZES', 'TEXT_CONTROL_GAP', 'textControlState' ],
          message    : 'The frame of a control is FieldShell: render it, with the slot of the control, instead of its classes.'
        } ]
      } ]
    }
  },

  {
    /** The layout section writes its own layout classes, but its outlines follow the rule of the package */
    name : 'suite/ui-outline',
    files: [ `${UI}/layout/**/*.{ts,tsx}` ],
    rules: {
      'no-restricted-syntax': [
        ...proedis.configs.tailwind.rules['no-restricted-syntax'],
        ...OUTLINE_SELECTORS
      ]
    }
  },

  {
    /**
     * The documentation site is the first consumer of the package and lays out the way an application
     * should: through the primitives. Only class contexts are checked here, a `className` or a `cn()`,
     * because the site is mostly prose and a sentence about a grid is not a grid.
     */
    name : 'suite/platform-layout',
    files: [ `${UI_DOCS}/**/*.{ts,tsx}` ],
    rules: {
      'no-restricted-syntax': [
        ...proedis.configs.tailwind.rules['no-restricted-syntax'],
        ...[ DISPLAY, GAP ].flatMap((pattern) => [
          { message: LAYOUT_MESSAGE, selector: `JSXAttribute[name.name=/className$/] Literal[value=/${pattern}/]:not(CallExpression[callee.name='cn'] Literal)` },
          { message: LAYOUT_MESSAGE, selector: `JSXAttribute[name.name=/className$/] TemplateElement[value.raw=/${pattern}/]` },
          { message: LAYOUT_MESSAGE, selector: `CallExpression[callee.name='cn'] Literal[value=/${pattern}/]` }
        ])
      ]
    }
  }
);
